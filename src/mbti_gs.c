/* 두 지표를 한 막대에 (왼쪽 비율만큼 하늘색, 나머지 보라). 이긴 쪽 이름은 노랗게 */
static void bar(const char *left_name, char l, int lv, const char *right_name, char r, int rv, int win_left)
{
	int i, total = lv + rv, cells = total ? (lv * 20 + total / 2) / total : 10;
	printf("    %s%s %c %2d" C_WHITE "  ", win_left ? C_YELLOW : C_GRAY, left_name, l, lv);
	printf(C_CYAN);
	for ( i = 0; i < cells; i++ ) printf("■");
	printf(C_MAGENTA);
	for ( ; i < 20; i++ ) printf("■");
	printf("  %s%2d %c %s" C_WHITE "\r\n", win_left ? C_GRAY : C_YELLOW, rv, r, right_name);
}

/* 글을 쪽으로 나눠 보여 준다. 쪽마다 같은 제목 */
static void show_paged(const char *title, const char *heading, const char *text)
{
	static char buf[16384];
	char *line, *next;
	int row = 0;
	wrap(text, 74, buf, sizeof(buf));
	header(title, "");
	printf("\r\n  " C_YELLOW "%s" C_WHITE "\r\n\r\n", heading);
	for ( line = buf; line && *line; line = next ) {
		next = strchr(line, '\n');
		if ( next ) *next++ = 0;
		if ( row == PAGE_ROWS ) {
			printf("\r\n " C_GRAY "[Enter] 다음 쪽" C_WHITE);
			wait_enter();
			header(title, "");
			printf("\r\n  " C_YELLOW "%s" C_GRAY " (이어서)" C_WHITE "\r\n\r\n", heading);
			row = 0;
		}
		printf("    %s\r\n", line);
		row++;
	}
	wait_enter();
}

static void show_result(void)
{
	int s[8];
	char code[5];
	int i, t = -1;
	char title[128];

	compute(s);
	/* 점수가 같으면 I, N, F, P (MBTI 규칙) */
	code[0] = s[0] > s[1] ? 'E' : 'I';
	code[1] = s[2] > s[3] ? 'S' : 'N';
	code[2] = s[4] > s[5] ? 'T' : 'F';
	code[3] = s[6] > s[7] ? 'J' : 'P';
	code[4] = 0;
	for ( i = 0; i < 16; i++ ) if ( !strcmp(types[i].code, code) ) t = i;
	if ( t < 0 ) return;

	sprintf(title, C_CYAN "성격 유형 검사 결과" C_WHITE);
	header(title, "");
	printf("\r\n    나의 유형은  " C_YELLOW "\033[7m %c  %c  %c  %c \033[0m" C_WHITE "  " C_YELLOW "%s" C_WHITE "\r\n\r\n",
			code[0], code[1], code[2], code[3], types[t].name);
	print_wrapped(types[t].summary, 4, C_CYAN);
	printf("\r\n");
	bar("외향", 'E', s[0], "내향", 'I', s[1], code[0] == 'E');
	bar("감각", 'S', s[2], "직관", 'N', s[3], code[1] == 'S');
	bar("사고", 'T', s[4], "감정", 'F', s[5], code[2] == 'T');
	bar("판단", 'J', s[6], "인식", 'P', s[7], code[3] == 'J');
	printf("\r\n");
	print_wrapped(types[t].keywords, 4, C_GREEN);
	printf("\r\n    " C_GRAY "이 검사는 성격을 진단하는 심리검사가 아니라 타고난 경향을 알아보는 것입니다." C_WHITE "\r\n");
	wait_enter();

	sprintf(title, C_CYAN "%s %s" C_WHITE, types[t].code, types[t].name);
	show_paged(title, "성격의 특징", types[t].desc);
	if ( types[t].extra1 && *types[t].extra1 ) show_paged(title, types[t].extra1_title, types[t].extra1);
	if ( types[t].extra2 && *types[t].extra2 ) show_paged(title, types[t].extra2_title, types[t].extra2);
}

