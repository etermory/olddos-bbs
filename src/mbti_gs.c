static void restore_term(void)
{
	if ( have_tio ) tcsetattr(0, TCSAFLUSH, &saved_tio);
}

static void leave(int code)
{
	printf(C_WHITE "\r\n");
	fflush(stdout);
	restore_term();
	exit(code);
}

static void on_hup(int sig)
{
	(void)sig;
	leave(1);
}

static void raw_mode(void)
{
	struct termios t;
	if ( tcgetattr(0, &saved_tio) != 0 ) return;
	have_tio = 1;
	t = saved_tio;
	t.c_iflag = IXON | IXANY;
	t.c_oflag &= ~OPOST;
	t.c_lflag &= ~(ICANON | ISIG | ECHO);
	t.c_cflag &= ~(PARENB | CSIZE);
	t.c_cflag |= CS8;
	t.c_cc[VMIN] = 1;
	t.c_cc[VTIME] = 0;
	tcsetattr(0, TCSAFLUSH, &t);
}

