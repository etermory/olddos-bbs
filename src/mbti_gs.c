static int vis(const char *s)		/* 색 코드를 뺀 화면 칸 수 (완성형 2 바이트 = 2 칸) */
{
	int n = 0;
	while ( *s ) {
		if ( *s == '\033' ) {
			while ( *s && !((*s >= 'A' && *s <= 'Z') || (*s >= 'a' && *s <= 'z')) ) s++;
			if ( *s ) s++;
			continue;
		}
		n++;
		s++;
	}
	return n;
}

