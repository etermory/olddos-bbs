/* 글을 width 칸에 맞춰 띄어쓰기에서 나눈다 (한글을 반으로 자르지 않는다).
   out 에 줄들을 '\n' 으로 이어 넣고 줄 수를 돌려준다. */
static int wrap(const char *s, int width, char *out, int outsize)
{
	int lines = 0, col = 0, n = 0;
	const char *p = s;
	while ( *p == ' ' ) p++;
	while ( *p ) {
		/* 다음 낱말 */
		const char *q = p;
		int wlen;
		while ( *q && *q != ' ' ) q++;
		wlen = q - p;
		if ( col > 0 && col + 1 + wlen > width ) {
			if ( n < outsize - 1 ) out[n++] = '\n';
			lines++;
			col = 0;
		} else if ( col > 0 ) {
			if ( n < outsize - 1 ) out[n++] = ' ';
			col++;
		}
		/* 한 줄보다 긴 낱말은 글자 단위로 */
		while ( wlen > 0 ) {
			int k = ((unsigned char)*p >= 0x80 && wlen > 1) ? 2 : 1;
			if ( col + k > width ) {
				if ( n < outsize - 1 ) out[n++] = '\n';
				lines++;
				col = 0;
			}
			while ( k-- > 0 ) {
				if ( n < outsize - 1 ) out[n++] = *p;
				p++;
				wlen--;
				col++;
			}
		}
		while ( *p == ' ' ) p++;
	}
	out[n] = 0;
	return col > 0 ? lines + 1 : lines;
}

/* indent 칸 들여서 나눈 글을 찍고 찍은 줄 수를 돌려준다 */
static int print_wrapped(const char *s, int indent, const char *color)
{
	static char buf[16384];
	char *line, *next;
	int lines = wrap(s, 78 - indent, buf, sizeof(buf));
	for ( line = buf; line && *line; line = next ) {
		next = strchr(line, '\n');
		if ( next ) *next++ = 0;
		printf("%*s%s%s" C_WHITE "\r\n", indent, "", color, line);
	}
	return lines;
}

